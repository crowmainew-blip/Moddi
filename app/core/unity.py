"""เกม Unity: ใช้ BepInEx + XUnity.AutoTranslator (MIT) ดักข้อความระหว่างเล่น แล้วส่งมาให้ moddi แปลสด

ขั้นตอน
1. ติดตั้ง BepInEx และ XUnity.AutoTranslator ลงโฟลเดอร์เกม (บันทึกรายการไฟล์ไว้ ถอนได้หมด)
2. ตั้งค่า XUnity ให้ส่งข้อความมาที่ moddi (Endpoint=CustomTranslate)
3. ระหว่างเล่น moddi แปลแล้วจำคำแปลไว้ในโปรเจกต์
4. คำแปลที่แก้แล้วเขียนลง BepInEx/Translation/th/Text/moddi.txt
   (XUnity ให้ความสำคัญไฟล์อื่นเหนือ _AutoGeneratedTranslations.txt เสมอ)
"""
import io
import json
import os
import re
import shutil
import struct
import urllib.request
import zipfile

from . import thai_shape

MANIFEST = "moddi_unity.json"
LANG = "th"
UA = {"User-Agent": "moddi-translator", "Accept": "application/vnd.github+json"}

# สำรองไว้เผื่อเรียก GitHub API ไม่ได้ (rate limit)
FALLBACK = {
    ("bepinex5", "x64"): "https://github.com/BepInEx/BepInEx/releases/download/v5.4.23.2/BepInEx_win_x64_5.4.23.2.zip",
    ("bepinex5", "x86"): "https://github.com/BepInEx/BepInEx/releases/download/v5.4.23.2/BepInEx_win_x86_5.4.23.2.zip",
}


# ---------------------------------------------------------------- detect
def _pe_arch(path):
    try:
        with open(path, "rb") as f:
            f.seek(0x3C)
            off = struct.unpack("<I", f.read(4))[0]
            f.seek(off + 4)
            machine = struct.unpack("<H", f.read(2))[0]
        return "x86" if machine == 0x14C else "x64"
    except Exception:
        return "x64"


def detect(game_dir):
    if not game_dir or not os.path.isdir(game_dir):
        return None
    for name in sorted(os.listdir(game_dir)):
        if not name.lower().endswith(".exe"):
            continue
        stem = name[:-4]
        data = os.path.join(game_dir, stem + "_Data")
        if not os.path.isdir(data):
            continue
        il2cpp = os.path.isfile(os.path.join(game_dir, "GameAssembly.dll"))
        mono = os.path.isdir(os.path.join(data, "Managed"))
        if not (il2cpp or mono):
            continue
        player = os.path.join(game_dir, "UnityPlayer.dll")
        arch = _pe_arch(player if os.path.isfile(player) else os.path.join(game_dir, name))
        bep = os.path.join(game_dir, "BepInEx")
        return {
            "engine": "Unity (IL2CPP)" if il2cpp else "Unity",
            "kind": "unity",
            "il2cpp": il2cpp,
            "arch": arch,
            "exe": name,
            "title": stem,
            "root": game_dir,
            "bepinex": os.path.isfile(os.path.join(bep, "core", "BepInEx.dll"))
                       or os.path.isfile(os.path.join(bep, "core", "BepInEx.Core.dll")),
            "xunity": os.path.isdir(os.path.join(bep, "plugins", "XUnity.AutoTranslator")),
            "managed": os.path.isfile(os.path.join(game_dir, MANIFEST)),
        }
    return None


# ---------------------------------------------------------------- downloads
def _get(url, timeout=60):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def _pick_asset(repo, pattern, tag_prefix=None, prerelease=False):
    rels = json.loads(_get(f"https://api.github.com/repos/{repo}/releases?per_page=40"))
    for rel in rels:
        if rel.get("draft") or (rel.get("prerelease") and not prerelease):
            continue
        if tag_prefix and not rel.get("tag_name", "").startswith(tag_prefix):
            continue
        for a in rel.get("assets", []):
            if re.fullmatch(pattern, a["name"]):
                return a["browser_download_url"], a["name"]
    raise ValueError(f"หาไฟล์ดาวน์โหลดของ {repo} ไม่เจอ")


def packages_for(info):
    """คืนรายการ (ชื่อ, url, ชื่อไฟล์) ที่ต้องโหลด"""
    arch = info["arch"]
    pkgs = []
    if info["il2cpp"]:
        if not info["bepinex"]:
            url, name = _pick_asset("BepInEx/BepInEx", rf"BepInEx-Unity\.IL2CPP-win-{arch}-6\.[\w.\-]+\.zip",
                                    tag_prefix="v6.", prerelease=True)
            pkgs.append(("BepInEx 6 (IL2CPP)", url, name))
        if not info["xunity"]:
            url, name = _pick_asset("bbepis/XUnity.AutoTranslator", r"XUnity\.AutoTranslator-BepInEx-IL2CPP-\d[\d.]*\.zip")
            pkgs.append(("XUnity.AutoTranslator", url, name))
        return pkgs
    if not info["bepinex"]:
        try:
            url, name = _pick_asset("BepInEx/BepInEx", rf"BepInEx_(win_)?{arch}_5[\d.]*\.zip", tag_prefix="v5.")
        except Exception:
            url = FALLBACK[("bepinex5", arch)]
            name = url.rsplit("/", 1)[1]
        pkgs.append(("BepInEx 5", url, name))
    if not info["xunity"]:
        url, name = _pick_asset("bbepis/XUnity.AutoTranslator", r"XUnity\.AutoTranslator-BepInEx-\d[\d.]*\.zip")
        pkgs.append(("XUnity.AutoTranslator", url, name))
    return pkgs


def _extract(zbytes, game_dir, added):
    root = os.path.realpath(game_dir)
    with zipfile.ZipFile(io.BytesIO(zbytes)) as z:
        for m in z.infolist():
            dest = os.path.realpath(os.path.join(game_dir, m.filename))
            if not dest.startswith(root + os.sep):
                continue  # กันไฟล์ใน zip ที่พยายามเขียนออกนอกโฟลเดอร์เกม
            rel = os.path.relpath(dest, root)
            if m.is_dir():
                if not os.path.isdir(dest):
                    os.makedirs(dest, exist_ok=True)
                    added["dirs"].append(rel)
                continue
            parent = os.path.dirname(dest)
            if not os.path.isdir(parent):
                os.makedirs(parent, exist_ok=True)
                added["dirs"].append(os.path.relpath(parent, root))
            if not os.path.exists(dest):
                added["files"].append(rel)
            elif rel not in added["files"] and rel not in added.setdefault("replaced", []):
                # ไฟล์เดิมของเกมที่ชื่อชนกัน: สำรองไว้ก่อน ถอนแล้วคืนให้
                bak = os.path.join(root, "moddi_unity_backup", rel)
                os.makedirs(os.path.dirname(bak), exist_ok=True)
                shutil.copy2(dest, bak)
                added["replaced"].append(rel)
            with z.open(m) as src, open(dest, "wb") as out:
                shutil.copyfileobj(src, out)


def _load_manifest(game_dir):
    p = os.path.join(game_dir, MANIFEST)
    if os.path.isfile(p):
        with open(p, encoding="utf-8") as f:
            return json.load(f)
    return {"files": [], "dirs": [], "replaced": [], "bepinex_preexisting": None}


def _save_manifest(game_dir, man):
    with open(os.path.join(game_dir, MANIFEST), "w", encoding="utf-8") as f:
        json.dump(man, f, ensure_ascii=False, indent=1)


def install_runtime(game_dir, progress=lambda msg, pct: None, fetch=None, package_list=None):
    info = detect(game_dir)
    if not info:
        raise ValueError("ไม่ใช่เกม Unity")
    man = _load_manifest(game_dir)
    if man["bepinex_preexisting"] is None:
        man["bepinex_preexisting"] = info["bepinex"]
    pkgs = package_list if package_list is not None else packages_for(info)
    for i, (label, url, _name) in enumerate(pkgs):
        progress(f"กำลังโหลด {label}", int(100 * i / max(1, len(pkgs))))
        data = (fetch or _get)(url, 300)
        progress(f"กำลังติดตั้ง {label}", int(100 * (i + 0.5) / max(1, len(pkgs))))
        _extract(data, game_dir, man)
        _save_manifest(game_dir, man)
    _save_manifest(game_dir, man)
    progress("ติดตั้งระบบแปลแล้ว", 100)


# ---------------------------------------------------------------- config
def _bep(game_dir, *p):
    return os.path.join(game_dir, "BepInEx", *p)


def write_config(game_dir, live_url=None, from_lang="en", font_fix=False, tmp_font=False):
    """ตั้งค่า XUnity: แก้เฉพาะคีย์ที่ moddi ต้องใช้ คีย์อื่นคงไว้ตามเดิม"""
    path = _bep(game_dir, "config", "AutoTranslatorConfig.ini")
    want = {
        "Service": {"Endpoint": "CustomTranslate" if live_url else "", "FallbackEndpoint": ""},
        "General": {"Language": LANG, "FromLanguage": from_lang},
        "Custom": {"Url": live_url or ""},
        "Behaviour": {"FallbackFontTextMeshPro": "Tahoma", "OverrideFont": "Tahoma" if font_fix else "",
                      "OverrideFontTextMeshPro": "Tahoma" if tmp_font else "",
                      "MaxCharactersPerTranslation": "500"},
    }
    lines = []
    if os.path.isfile(path):
        with open(path, encoding="utf-8-sig") as f:
            lines = f.read().splitlines()
    out, section, done = [], None, {s: set() for s in want}

    def flush(sec):
        if sec in want:
            for k, v in want[sec].items():
                if k not in done[sec]:
                    out.append(f"{k}={v}")
                    done[sec].add(k)

    for line in lines:
        m = re.match(r"\s*\[(.+?)\]\s*$", line)
        if m:
            flush(section)
            section = m.group(1)
            out.append(line)
            continue
        km = re.match(r"\s*([^=;\s]+)\s*=", line)
        if section in want and km and km.group(1) in want[section]:
            k = km.group(1)
            out.append(f"{k}={want[section][k]}")
            done[section].add(k)
            continue
        out.append(line)
    flush(section)
    for sec in want:
        if not done[sec]:
            out.append(f"[{sec}]")
            flush(sec)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


def read_config(game_dir):
    path = _bep(game_dir, "config", "AutoTranslatorConfig.ini")
    cfg, section = {}, None
    if os.path.isfile(path):
        with open(path, encoding="utf-8-sig") as f:
            for line in f:
                m = re.match(r"\s*\[(.+?)\]\s*$", line)
                if m:
                    section = m.group(1)
                    continue
                km = re.match(r"\s*([^=;\s]+)\s*=([^;]*)", line)
                if km:
                    cfg[f"{section}.{km.group(1)}"] = km.group(2).strip()
    return cfg


# ---------------------------------------------------------------- translation files (รูปแบบของ XUnity)
def encode(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "/" and i + 1 < len(s) and s[i + 1] == "/":
            out.append("\\/\\/")
            i += 2
            continue
        out.append({"\\": "\\\\", "=": "\\=", "\n": "\\n", "\r": "\\r"}.get(c, c))
        i += 1
    return "".join(out)


def decode_line(line):
    """แยก key=value ตามกติกาของ XUnity คืนค่า (key, value) หรือ None"""
    if not line or line.startswith("//"):
        return None
    parts, buf, esc = [], [], False
    i = 0
    while i < len(line):
        c = line[i]
        if esc:
            esc = False
            if c in "=\\":
                buf.append(c)
            elif c == "n":
                buf.append("\n")
            elif c == "r":
                buf.append("\r")
            elif c == "u" and i + 4 < len(line):
                buf.append(chr(int(line[i + 1:i + 5], 16)))
                i += 4
            elif c == "/":
                buf.append("/")
            else:
                buf.append("\\" + c)
        elif c == "\\":
            esc = True
        elif c == "=" and not parts:
            parts.append("".join(buf))
            buf = []
        else:
            buf.append(c)
        i += 1
    if len(parts) != 1:
        return None
    parts.append("".join(buf))
    return parts[0], parts[1]


def text_dir(game_dir):
    return _bep(game_dir, "Translation", LANG, "Text")


def read_auto(game_dir):
    """อ่านคำแปลที่ XUnity บันทึกไว้เอง"""
    out = {}
    p = os.path.join(text_dir(game_dir), "_AutoGeneratedTranslations.txt")
    if os.path.isfile(p):
        with open(p, encoding="utf-8-sig", errors="replace") as f:
            for line in f.read().splitlines():
                kv = decode_line(line)
                if kv and kv[1]:
                    out[kv[0]] = thai_shape.unshape(kv[1])
    return out


def write_translations(game_dir, translations, shape=True):
    d = text_dir(game_dir)
    os.makedirs(d, exist_ok=True)
    man = _load_manifest(game_dir)
    rel = os.path.relpath(os.path.join(d, "moddi.txt"), game_dir)
    if rel not in man["files"] and not os.path.exists(os.path.join(d, "moddi.txt")):
        man["files"].append(rel)
        _save_manifest(game_dir, man)
    items = [(k, v) for k, v in translations.items() if v and v != k]
    with open(os.path.join(d, "moddi.txt"), "w", encoding="utf-8") as f:
        f.write("// moddi — คำแปลที่ตรวจแก้แล้ว (มีความสำคัญเหนือ _AutoGeneratedTranslations.txt)\n")
        for k, v in items:
            f.write(encode(k) + "=" + encode(thai_shape.shape(v) if shape else v) + "\n")
    return len(items)


def uninstall(game_dir):
    """ถอนทุกอย่างที่ moddi ใส่ลงไป ถ้า BepInEx มีอยู่ก่อนแล้ว จะถอนเฉพาะของ moddi"""
    man_path = os.path.join(game_dir, MANIFEST)
    if not os.path.isfile(man_path):
        raise ValueError("เกมนี้ยังไม่ได้ติดตั้งระบบแปลของ moddi")
    man = _load_manifest(game_dir)
    root = os.path.realpath(game_dir)
    if not man.get("bepinex_preexisting"):
        bep = os.path.join(game_dir, "BepInEx")
        if os.path.isdir(bep):
            shutil.rmtree(bep)  # รวม config / log / cache ที่ BepInEx สร้างตอนเล่น
    for rel in man.get("files", []):
        p = os.path.realpath(os.path.join(game_dir, rel))
        if p.startswith(root + os.sep) and os.path.isfile(p):
            os.remove(p)
    for rel in man.get("replaced", []):
        bak = os.path.join(game_dir, "moddi_unity_backup", rel)
        if os.path.isfile(bak):
            os.makedirs(os.path.dirname(os.path.join(game_dir, rel)), exist_ok=True)
            shutil.move(bak, os.path.join(game_dir, rel))
    if os.path.isdir(os.path.join(game_dir, "moddi_unity_backup")):
        shutil.rmtree(os.path.join(game_dir, "moddi_unity_backup"))
    for rel in sorted(man.get("dirs", []), key=len, reverse=True):
        p = os.path.realpath(os.path.join(game_dir, rel))
        if p.startswith(root + os.sep) and os.path.isdir(p) and not os.listdir(p):
            os.rmdir(p)
    os.remove(man_path)
